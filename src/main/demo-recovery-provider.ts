import { createHash, randomUUID } from "node:crypto";
import { mkdir, mkdtemp, open, lstat, realpath } from "node:fs/promises";
import type { FileHandle } from "node:fs/promises";
import type { BigIntStats } from "node:fs";
import path from "node:path";
import type { AuditSink } from "./audit-sink";
import { createAuditEvent } from "../shared/audit";
import type { RecoveryWorkflowProvider, WorkflowSource, WorkflowRecord, WorkflowAnalysis, RecoveryProviderResult } from "../shared/recovery-provider";
import { validateDemoProviderResult } from "../shared/recovery-provider";
import { isSafeWorkingCopyPath } from "./working-copy-engine";
import { validateImageId } from "../shared/image-inspection";

interface FixtureRecord { public: WorkflowRecord; offset: number; length: number }
interface Fixture { public: WorkflowSource; filePath: string; identity: BigIntStats; digest: string; records: FixtureRecord[] }
export interface DemoRecoveryProviderOptions {
  /** Trusted application-owned directory. Never a selected device/volume path. */
  fixtureDirectory: string;
  chooseOutput(request: { operation: "acquisition" | "recovery"; source: WorkflowSource; record: WorkflowRecord | null; suggestedName: string }): Promise<string | null>;
  audit?: AuditSink;
}
const label = "DEMO — synthetic fixture; no real acquisition or deleted-file recovery";
const sha = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");
const same = (a: BigIntStats, b: BigIntStats) => a.isFile() && a.dev === b.dev && a.ino === b.ino && a.size === b.size && a.mtimeNs === b.mtimeNs && a.ctimeNs === b.ctimeNs;

/** Synthetic regular files only. NTFS/exFAT records come from private fixture maps, not a filesystem parser. */
export function createDemoRecoveryProvider(options: DemoRecoveryProviderOptions): RecoveryWorkflowProvider {
  let fixtures: Fixture[] = [], sourceDirectory = "", initialization: Promise<void> | null = null, closed = false, busy = false;
  let current: AbortController | null = null, pending: Promise<RecoveryProviderResult> | null = null;
  const assertOpen = () => { if (closed) throw new Error("Demo provider is closed."); };
  async function initialize() {
    assertOpen();
    if (!initialization) initialization = (async () => {
      if (!path.isAbsolute(options.fixtureDirectory) || !isSafeWorkingCopyPath(path.join(options.fixtureDirectory, "fixture.img"))) throw new Error("Demo fixtures require a trusted local regular-file directory.");
      await mkdir(options.fixtureDirectory, { recursive: true });
      sourceDirectory = await mkdtemp(path.join(await realpath(options.fixtureDirectory), "demo-session-"));
      for (const filesystem of ["NTFS", "exFAT"] as const) {
        const bytes = Buffer.alloc(64 * 1024); bytes[0] = 0xeb; bytes[510] = 0x55; bytes[511] = 0xaa;
        if (filesystem === "NTFS") {
          bytes.write("NTFS    ", 3); bytes.writeUInt16LE(512, 11); bytes[13] = 1; bytes.writeBigUInt64LE(128n, 40); bytes.writeBigUInt64LE(4n, 48); bytes.writeBigUInt64LE(8n, 56);
        } else {
          bytes.write("EXFAT   ", 3); bytes.writeBigUInt64LE(128n, 72); bytes.writeUInt32LE(24, 80); bytes.writeUInt32LE(1, 84); bytes.writeUInt32LE(25, 88); bytes.writeUInt32LE(100, 92); bytes.writeUInt32LE(2, 96); bytes[108] = 9; bytes[110] = 1;
        }
        const records: FixtureRecord[] = [];
        for (const [index, state] of (["allocated", "deleted"] as const).entries()) {
          const payload = Buffer.from(`DEMO ${filesystem} ${state} example payload. This is synthetic data from a fixture map, not a recovered file.\n`), offset = 16384 + index * 4096;
          payload.copy(bytes, offset);
          records.push({ public: { recordId: randomUUID(), name: `${state}-demo.txt`, state, sizeBytes: payload.length, evidence: "synthetic-record-map",
            warnings: [label, "Record metadata is generated by the demo provider; no NTFS/exFAT file-record analysis was performed."] }, offset, length: payload.length });
        }
        const filePath = path.join(sourceDirectory, `${filesystem.toLowerCase()}-demo.img`), writer = await open(filePath, "wx", 0o600);
        try { await writer.writeFile(bytes); await writer.sync(); } finally { await writer.close(); }
        fixtures.push({ filePath, identity: await lstat(filePath, { bigint: true }), digest: sha(bytes), records,
          public: { sourceId: randomUUID(), label: `DEMO ${filesystem} synthetic regular image`, filesystem, sizeBytes: bytes.length, provenance: "synthetic-fixture",
            warnings: [label, "Boot geometry is illustrative; synthetic record maps are not decoded from filesystem structures."] } });
      }
    })();
    await initialization; assertOpen();
  }
  async function lookup(sourceId: string) {
    validateImageId(sourceId);
    await initialize(); const source = fixtures.find(f => f.public.sourceId === sourceId);
    if (!source) throw new Error("Unknown demo source ID. Physical paths and external images are not accepted.");
    return source;
  }
  async function verify(source: Fixture, handle?: FileHandle) {
    if (!same(await lstat(source.filePath, { bigint: true }), source.identity) || handle && !same(await handle.stat({ bigint: true }), source.identity)) throw new Error("Demo source fixture changed; create a fresh provider session.");
  }
  async function analyze(sourceId: string): Promise<WorkflowAnalysis> {
    const source = await lookup(sourceId); await verify(source);
    return { source: structuredClone(source.public), mode: "demo", records: source.records.map(record => structuredClone(record.public)), analysisKind: "synthetic-record-map",
      limitations: [label, "NTFS/exFAT records are predefined demo examples, including a synthetic deleted marker. No real filesystem inventory, file-chain reconstruction or deleted-file recovery occurred."] };
  }
  async function separateOutput(chosen: string) {
    if (!isSafeWorkingCopyPath(chosen) || !isSafeWorkingCopyPath(`${chosen}.oscp.json`)) throw new Error("Select a safe new regular output filename.");
    const directory = await realpath(path.dirname(chosen)), relative = path.relative(sourceDirectory, directory);
    if (!relative || relative !== ".." && !relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative)) throw new Error("Demo output must be separate from the source fixture directory.");
    for (const protectedPath of options.audit?.protectedPaths ?? []) {
      const auditDirectory = await realpath(path.dirname(protectedPath)), relativeAudit = path.relative(auditDirectory, directory);
      if (!relativeAudit || relativeAudit !== ".." && !relativeAudit.startsWith(`..${path.sep}`) && !path.isAbsolute(relativeAudit)) throw new Error("Demo output cannot be written inside an audit directory.");
    }
    const canonical = path.join(directory, path.basename(chosen));
    for (const candidate of [canonical, `${canonical}.oscp.json`]) {
      try { await lstat(candidate); throw new Error("Demo output and sidecar must be new files; existing data is never overwritten."); }
      catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
    }
    return canonical;
  }
  async function operation(operation: "acquisition" | "recovery", sourceId: string, recordId: string | null, signal?: AbortSignal): Promise<RecoveryProviderResult> {
    assertOpen(); if (busy) throw new Error("A demo operation is already active."); busy = true;
    const abort = new AbortController(); current = abort;
    const forward = () => abort.abort(); signal?.addEventListener("abort", forward, { once: true }); if (signal?.aborted) abort.abort();
    const check = () => { assertOpen(); if (abort.signal.aborted) throw new Error("Demo simulation cancelled; any partial output was retained."); };
    const result: RecoveryProviderResult = { mode: "demo", operation, state: "failed", operationId: randomUUID(), sourceId, recordId, simulation: true,
      physicalAcquisitionPerformed: false, recoveryPerformed: false, outputPath: null, metadataPath: null, bytesWritten: 0, sourceSha256: null, outputSha256: null,
      partialOutputRetained: false, error: null, notice: label };
    let source: Fixture | undefined, input: FileHandle | undefined, output: FileHandle | undefined, manifest: FileHandle | undefined;
    let outputIdentity: BigIntStats | undefined, manifestIdentity: BigIntStats | undefined;
    const persist = async () => {
      if (!manifest) return;
      const bytes = Buffer.from(JSON.stringify({ schemaVersion: 1, generatedAtUtc: new Date().toISOString(), source: source?.public,
        analysisKind: "synthetic-record-map", realFilesystemAnalysisPerformed: false, limitations: [label, "Demo separation is between regular files/directories, not independent physical media."], ...result }, null, 2) + "\n");
      await manifest.truncate(0); let written = 0;
      while (written < bytes.length) { const n = await manifest.write(bytes, written, bytes.length - written, written); if (!n.bytesWritten) throw new Error("Demo metadata write stalled."); written += n.bytesWritten; }
      await manifest.sync(); const visible = await lstat(result.metadataPath!, { bigint: true });
      if (!visible.isFile() || visible.isSymbolicLink() || visible.dev !== manifestIdentity?.dev || visible.ino !== manifestIdentity?.ino) throw new Error("Demo metadata path changed.");
    };
    try {
      check(); source = await lookup(sourceId); await verify(source); check();
      const record = recordId === null ? null : source.records.find(value => value.public.recordId === recordId);
      if (operation === "recovery" && !record) throw new Error("Unknown synthetic record ID; arbitrary offsets and source paths are not accepted.");
      const chosen = await options.chooseOutput({ operation, source: structuredClone(source.public), record: record ? structuredClone(record.public) : null,
        suggestedName: operation === "acquisition" ? `DEMO-${source.public.filesystem}-copy.img` : `DEMO-${record!.public.name}` });
      check(); if (chosen === null) { result.state = "cancelled"; return validateDemoProviderResult(result); }
      const outputPath = await separateOutput(chosen); result.outputPath = outputPath; result.metadataPath = `${outputPath}.oscp.json`;
      await verify(source); check(); input = await open(source.filePath, "r"); await verify(source, input);
      if (options.audit) await options.audit.append(createAuditEvent({ type: "operation.start", result: "success", target: source.public.sourceId,
        details: { operation: `demo-${operation}-simulation`, simulation: true, physicalAcquisitionPerformed: false, recoveryPerformed: false, operationId: result.operationId } }));
      check(); await separateOutput(outputPath); output = await open(outputPath, "wx+", 0o600); outputIdentity = await output.stat({ bigint: true }); result.partialOutputRetained = true;
      manifest = await open(result.metadataPath, "wx+", 0o600); manifestIdentity = await manifest.stat({ bigint: true }); await persist();
      const offset = record?.offset ?? 0, length = record?.length ?? source.public.sizeBytes, digest = createHash("sha256");
      let copied = 0;
      while (copied < length) {
        check(); await verify(source, input); const bytes = Buffer.alloc(Math.min(4096, length - copied));
        const received = await input.read(bytes, 0, bytes.length, offset + copied); if (received.bytesRead !== bytes.length) throw new Error("Demo source ended during copying.");
        await verify(source, input); check(); let sent = 0;
        while (sent < bytes.length) { check(); const wrote = await output.write(bytes, sent, bytes.length - sent, copied + sent); if (!wrote.bytesWritten) throw new Error("Demo output write stalled."); sent += wrote.bytesWritten; result.bytesWritten += wrote.bytesWritten; }
        digest.update(bytes); copied += bytes.length;
      }
      await output.sync(); check();
      const outputDigest = createHash("sha256"), buffer = Buffer.alloc(4096); let position = 0;
      while (position < length) { check(); const read = await output.read(buffer, 0, Math.min(buffer.length, length - position), position); if (!read.bytesRead) throw new Error("Demo output verification ended early."); outputDigest.update(buffer.subarray(0, read.bytesRead)); position += read.bytesRead; }
      result.sourceSha256 = digest.digest("hex"); result.outputSha256 = outputDigest.digest("hex");
      const visible = await lstat(outputPath, { bigint: true });
      if (result.sourceSha256 !== result.outputSha256 || !visible.isFile() || visible.isSymbolicLink() || visible.dev !== outputIdentity.dev || visible.ino !== outputIdentity.ino || visible.size !== BigInt(length)) throw new Error("Demo output identity or SHA-256 verification failed.");
      await verify(source, input);
      // Verify the complete fixture is unchanged, including bytes outside the selected record.
      const whole = Buffer.alloc(source.public.sizeBytes), complete = await input.read(whole, 0, whole.length, 0);
      if (complete.bytesRead !== whole.length || sha(whole) !== source.digest) throw new Error("Demo source fixture content changed.");
      await input.close(); input = undefined; await output.close(); output = undefined; check();
      if (options.audit) await options.audit.append(createAuditEvent({ type: "operation.complete", result: "success", target: source.public.sourceId,
        details: { operation: `demo-${operation}-simulation`, operationId: result.operationId, simulation: true, physicalAcquisitionPerformed: false, recoveryPerformed: false, bytes: result.bytesWritten, outputSha256: result.outputSha256 } }));
      check(); result.state = "simulated"; result.partialOutputRetained = false; await persist();
      return validateDemoProviderResult(result);
    } catch (error) {
      result.state = abort.signal.aborted || closed ? "cancelled" : "failed"; result.error = (error as Error).message;
      if (outputIdentity) result.partialOutputRetained = true;
      try { await persist(); } catch { result.error += " Demo metadata could not be finalized."; }
      if (options.audit) { try { await options.audit.append(createAuditEvent({ type: "operation.failure", result: result.state === "cancelled" ? "interrupted" : "failure", target: source?.public.sourceId,
        details: { operation: `demo-${operation}-simulation`, operationId: result.operationId, simulation: true, physicalAcquisitionPerformed: false, recoveryPerformed: false, message: result.error } })); } catch { result.error += " Demo audit failure recording unavailable."; } }
      return validateDemoProviderResult(result);
    } finally {
      const cleanup = await Promise.allSettled([input?.close(), output?.close(), manifest?.close()]);
      if (cleanup.some(value => value.status === "rejected")) { result.state = "failed"; result.error = "Demo file handles did not close cleanly."; }
      signal?.removeEventListener("abort", forward); current = null; busy = false;
    }
  }
  const start = (kind: "acquisition" | "recovery", sourceId: string, recordId: string | null, signal?: AbortSignal) => {
    validateImageId(sourceId); if (recordId !== null) validateImageId(recordId);
    if (busy) return Promise.reject(new Error("A demo operation is already active."));
    const action = operation(kind, sourceId, recordId, signal); pending = action;
    void action.finally(() => { if (pending === action) pending = null; }).catch(() => undefined); return action;
  };
  return {
    getCapabilities: () => ({ mode: "demo", acquisition: "simulation-only", recovery: "simulation-only", physicalExecution: false, reason: label }),
    async listSources() { await initialize(); for (const source of fixtures) await verify(source); return fixtures.map(source => structuredClone(source.public)); },
    analyze,
    acquire: (sourceId, signal) => start("acquisition", sourceId, null, signal),
    recover: (sourceId, recordId, signal) => start("recovery", sourceId, recordId, signal),
    async shutdown() { closed = true; current?.abort(); await Promise.allSettled([initialization, pending]); },
  };
}
